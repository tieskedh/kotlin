package generators

import templates.Aggregates
import templates.COPYRIGHT_NOTICE
import templates.Elements
import templates.Family
import templates.KotlinTarget
import templates.MemberTemplate
import templates.autoGeneratedWarning
import java.io.File
import java.io.StringWriter
import kotlin.system.exitProcess

/**
 * Materializes only the Common collection templates whose dependency closure the experimental
 * Kotlin/.NET stdlib currently supports.
 *
 * This is a temporary source-product allowlist, not a .NET algorithm fork. Every emitted member
 * is built by the same Common template object used for the mature targets. Delete this generator
 * once Kotlin/.NET can compile the complete Common generated collection corpus.
 */
fun main(args: Array<String>) {
    if (args.size != 1) {
        println("Parameters:\n    <kotlin-base-dir>")
        exitProcess(1)
    }

    val baseDir = File(args.single())
    val outputFile = baseDir.resolve(
        "libraries/stdlib/dotnet/common/src/generated/_DotNetBootstrapCollections.kt"
    )
    val commonCollectionsFile =
        baseDir.resolve("libraries/stdlib/src/kotlin/collections/Collections.kt")
    val commonArraysFile =
        baseDir.resolve("libraries/stdlib/common/src/generated/_Arrays.kt")
    val arrayAsListDeclaration = extractCommonDeclaration(
        commonArraysFile,
        "public expect fun <T> Array<out T>.asList(): List<T>",
    )
    val lastIndexDeclaration = extractCommonDeclaration(
        commonCollectionsFile,
        "public val <T> List<T>.lastIndex: Int",
    )
    val checkCountOverflowDeclaration = extractCommonUndocumentedDeclaration(
        commonCollectionsFile,
        "internal expect fun checkCountOverflow(count: Int): Int",
    )
    val throwCountOverflowDeclaration = extractCommonUndocumentedDeclaration(
        commonCollectionsFile,
        "internal fun throwCountOverflow()",
    )
    val selectedTemplates = sequenceOf(
        Aggregates.f_any selectedFor setOf(Family.Iterables),
        Aggregates.f_count selectedFor setOf(Family.Iterables),
        Aggregates.f_none selectedFor setOf(Family.Iterables),
        Elements.f_elementAtOrNull selectedFor setOf(Family.Iterables),
        Elements.f_first selectedFor setOf(Family.Iterables, Family.Lists),
        Elements.f_firstOrNull selectedFor setOf(Family.Iterables, Family.Lists),
        Elements.f_getOrNull selectedFor setOf(Family.Lists),
        Elements.f_last selectedFor setOf(Family.Iterables, Family.Lists),
        Elements.f_lastOrNull selectedFor setOf(Family.Iterables, Family.Lists),
        Elements.f_single selectedFor setOf(Family.Iterables, Family.Lists),
        Elements.f_singleOrNull selectedFor setOf(Family.Iterables, Family.Lists),
    )
    val members = selectedTemplates
        .flatMap { [template, families] ->
            template.instantiate(listOf(KotlinTarget.Common)).filter { member ->
                member.family in families
            }
        }
        .sortedBy { it.sortingSignature }
        .toList()

    val generatedSource = StringWriter()
    generatedSource.appendLine(COPYRIGHT_NOTICE)
    generatedSource.appendLine("package kotlin.collections")
    generatedSource.appendLine()
    generatedSource.appendLine(autoGeneratedWarning("GenerateDotNetBootstrapCollections.kt"))
    generatedSource.appendLine(arrayAsListDeclaration)
    generatedSource.appendLine()
    generatedSource.appendLine(lastIndexDeclaration)
    generatedSource.appendLine()
    generatedSource.appendLine(checkCountOverflowDeclaration)
    generatedSource.appendLine()
    generatedSource.appendLine(throwCountOverflowDeclaration)
    generatedSource.appendLine()
    for (member in members) {
        member.build(generatedSource)
    }
    val normalizedSource = generatedSource.toString()
        .replace("\r\n", "\n")
        .lineSequence()
        .joinToString("\n") { line -> line.trimEnd() }
        .trimEnd() + "\n"
    outputFile.parentFile.mkdirs()
    outputFile.writeText(normalizedSource, Charsets.UTF_8)
}

private infix fun MemberTemplate.selectedFor(families: Set<Family>): Pair<MemberTemplate, Set<Family>> =
    this to families

/**
 * Copies one complete declaration from an authoritative Common source file. The unique declaration
 * header is deliberately a hard generation contract: upstream movement or signature changes fail
 * instead of leaving the bootstrap projection silently stale.
 */
private fun extractCommonDeclaration(sourceFile: File, declarationHeader: String): String {
    val source = sourceFile.readText().replace("\r\n", "\n")
    val declarationIndex = source.indexOf(declarationHeader)
    check(declarationIndex >= 0) {
        "Cannot find Common declaration '$declarationHeader' in ${sourceFile.path}"
    }
    check(source.indexOf(declarationHeader, declarationIndex + declarationHeader.length) < 0) {
        "Common declaration header '$declarationHeader' is not unique in ${sourceFile.path}"
    }
    val documentationIndex = source.lastIndexOf("/**", declarationIndex)
    check(documentationIndex >= 0) {
        "Cannot find KDoc for Common declaration '$declarationHeader' in ${sourceFile.path}"
    }
    val nextDocumentationIndex = source.indexOf("\n/**", declarationIndex)
    check(nextDocumentationIndex >= 0) {
        "Cannot find the end of Common declaration '$declarationHeader' in ${sourceFile.path}"
    }
    return source.substring(documentationIndex, nextDocumentationIndex).trimEnd()
}

/**
 * Copies one annotation-led declaration that intentionally has no KDoc. Blank declaration
 * boundaries are part of the fail-closed contract, so an upstream regrouping requires review.
 */
private fun extractCommonUndocumentedDeclaration(sourceFile: File, declarationHeader: String): String {
    val source = sourceFile.readText().replace("\r\n", "\n")
    val declarationIndex = source.indexOf(declarationHeader)
    check(declarationIndex >= 0) {
        "Cannot find Common declaration '$declarationHeader' in ${sourceFile.path}"
    }
    check(source.indexOf(declarationHeader, declarationIndex + declarationHeader.length) < 0) {
        "Common declaration header '$declarationHeader' is not unique in ${sourceFile.path}"
    }
    val declarationStart = source.lastIndexOf("\n\n", declarationIndex)
    check(declarationStart >= 0) {
        "Cannot find the start of Common declaration '$declarationHeader' in ${sourceFile.path}"
    }
    val declarationEnd = source.indexOf("\n\n", declarationIndex)
    check(declarationEnd >= 0) {
        "Cannot find the end of Common declaration '$declarationHeader' in ${sourceFile.path}"
    }
    return source.substring(declarationStart + 2, declarationEnd).trimEnd()
}
